"use strict";
/* Sideshow preload — exposes a minimal API to the panel. The OAuth
   client secret never reaches the renderer; it stays in the main process. */
const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("sideshow", {
  platform: process.platform,
  copy: (text) => ipcRenderer.invoke("sideshow:copy", text),
  hide: () => ipcRenderer.invoke("sideshow:hide"),
  openSettings: () => ipcRenderer.invoke("sideshow:open-settings"),
  openHelp: () => ipcRenderer.invoke("sideshow:open-help"),
  closeSettings: () => ipcRenderer.invoke("sideshow:close-settings"),
  configStatus: () => ipcRenderer.invoke("sideshow:config-status"),
  firebaseConfig: () => ipcRenderer.invoke("sideshow:firebase-config"),
  signIn: () => ipcRenderer.invoke("sideshow:sign-in"),
  signOut: () => ipcRenderer.invoke("sideshow:sign-out"),
  refreshToken: () => ipcRenderer.invoke("sideshow:refresh-token"),
  openConfigFolder: () => ipcRenderer.invoke("sideshow:open-config-folder"),
  getHotkey: () => ipcRenderer.invoke("sideshow:get-hotkey"),
  setHotkey: (acc) => ipcRenderer.invoke("sideshow:set-hotkey", acc),
  resetHotkey: () => ipcRenderer.invoke("sideshow:reset-hotkey"),
  getGesture: () => ipcRenderer.invoke("sideshow:get-gesture"),
  recordGesture: () => ipcRenderer.invoke("sideshow:record-gesture"),
  clearGesture: () => ipcRenderer.invoke("sideshow:clear-gesture"),
  getDoubleTapKey: () => ipcRenderer.invoke("sideshow:get-doubletap-key"),
  setDoubleTapKey: (name) => ipcRenderer.invoke("sideshow:set-doubletap-key", name),
  captureDoubleTapKey: () => ipcRenderer.invoke("sideshow:capture-doubletap-key"),
  getLongClick: () => ipcRenderer.invoke("sideshow:get-longclick"),
  recordLongClick: () => ipcRenderer.invoke("sideshow:record-longclick"),
  clearLongClick: () => ipcRenderer.invoke("sideshow:clear-longclick"),
  getAppearance: () => ipcRenderer.invoke("sideshow:get-appearance"),
  setAppearance: (value) => ipcRenderer.invoke("sideshow:set-appearance", value),
  getTransparency: () => ipcRenderer.invoke("sideshow:get-transparency"),
  setTransparency: (value) => ipcRenderer.invoke("sideshow:set-transparency", value),
  getBubbleOptions: () => ipcRenderer.invoke("sideshow:get-bubble-options"),
  setBubbleOptions: (value) => ipcRenderer.invoke("sideshow:set-bubble-options", value),
  getPosition: () => ipcRenderer.invoke("sideshow:get-position"),
  setPosition: (value) => ipcRenderer.invoke("sideshow:set-position", value),
  reportContentHeight: (h) => ipcRenderer.send("sideshow:content-height", h),
  setIgnoreMouseEvents: (ignore) => ipcRenderer.invoke("sideshow:ignore-mouse", ignore),
  dragStart: () => ipcRenderer.invoke("sideshow:drag-start"),
  dragMove: (dx, dy) => ipcRenderer.invoke("sideshow:drag-move", dx, dy),
  dragEnd: (moved) => ipcRenderer.invoke("sideshow:drag-end", moved),
  getSound: () => ipcRenderer.invoke("sideshow:get-sound"),
  setSound: (enabled) => ipcRenderer.invoke("sideshow:set-sound", enabled),
  getSoundStyle: () => ipcRenderer.invoke("sideshow:get-sound-style"),
  setSoundStyle: (value) => ipcRenderer.invoke("sideshow:set-sound-style", value),
  getCopyAllFormat: () => ipcRenderer.invoke("sideshow:get-copy-all-format"),
  setCopyAllFormat: (value) => ipcRenderer.invoke("sideshow:set-copy-all-format", value),
  getTooltips: () => ipcRenderer.invoke("sideshow:get-tooltips"),
  setTooltips: (enabled) => ipcRenderer.invoke("sideshow:set-tooltips", enabled),
  getMotion: () => ipcRenderer.invoke("sideshow:get-motion"),
  setMotion: (value) => ipcRenderer.invoke("sideshow:set-motion", value),
  setMotionEffective: (value) => ipcRenderer.invoke("sideshow:motion-effective", value),
  getReminders: () => ipcRenderer.invoke("sideshow:get-reminders"),
  setReminders: (enabled) => ipcRenderer.invoke("sideshow:set-reminders", enabled),
  getAccent: () => ipcRenderer.invoke("sideshow:get-accent"),
  setAccent: (value) => ipcRenderer.invoke("sideshow:set-accent", value),
  getCalendar: () => ipcRenderer.invoke("sideshow:get-calendar"),
  setCalendar: (value) => ipcRenderer.invoke("sideshow:set-calendar", value),
  getHiddenEvents: () => ipcRenderer.invoke("sideshow:get-hidden-events"),
  setHiddenEvents: (ids) => ipcRenderer.invoke("sideshow:set-hidden-events", ids),
  listCalendars: () => ipcRenderer.invoke("sideshow:list-calendars"),
  getCalendarEvents: (calendarIds) => ipcRenderer.invoke("sideshow:get-calendar-events", calendarIds),
  eventsUpdated: (list) => ipcRenderer.invoke("sideshow:events-updated", list),
  onOpenEvent: (fn) => ipcRenderer.on("sideshow:open-event", (_e, id) => fn(id)),
  onSettingsChanged: (fn) => ipcRenderer.on("sideshow:settings-changed", (_e, key) => fn(key)),
  onSettingsWindow: (fn) => ipcRenderer.on("sideshow:settings-window", (_e, open) => fn(open)),
  onPanelShowing: (fn) => ipcRenderer.on("sideshow:panel-showing", (_e, data) => fn(data)),
  onPanelHiding: (fn) => ipcRenderer.on("sideshow:panel-hiding", () => fn()),
  onAuthToken: (fn) => ipcRenderer.on("sideshow:auth-token", (_e, data) => fn(data)),
  onAuthError: (fn) => ipcRenderer.on("sideshow:auth-error", () => fn()),
  onConfigMissing: (fn) => ipcRenderer.on("sideshow:config-missing", (_e, st) => fn(st)),
});
